export const featuredProducts = products.filter((p) => p.featured);

export function recommend(need: Need, goal: Goal): Product[] {
  return products
    .map((p) => {
      let score = 0;
      if (p.goals.includes(goal)) score += 4;
      if (p.needs.includes(need)) score += 3;
      if (p.category === (need === "food" ? "food" : need === "care" ? "cosmetics" : "supplements"))
        score += 1;
      return { p, score };
    })
    .filter(({ score }) => score > 0)
    .sort((a, b) => b.score - a.score || a.p.name.sr.localeCompare(b.p.name.sr))
    .slice(0, 3)
    .map(({ p }) => p);
}

